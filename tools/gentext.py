for line in read("BidiMirroring.txt"):
    line = line.split("#")[0].strip()
    if not line:
        continue
    p = [x.strip() for x in line.split(";")]
    mirror.append((int(p[0], 16), int(p[1], 16)))
out.append("const Mapping kMirror[] = {\n")
for cp, m in sorted(mirror):
    out.append("  {0x%X,0x%X},\n" % (cp, m))
