# Bidi paired brackets: code point, pair, type (o/c)
brackets = []
for line in read("BidiBrackets.txt"):
    line = line.split("#")[0].strip()
    if not line:
        continue
    p = [x.strip() for x in line.split(";")]
    brackets.append((int(p[0], 16), int(p[1], 16), p[2]))
out.append("const Bracket kBrackets[] = {\n")
for cp, pair, t in sorted(brackets):
    out.append("  {0x%X,0x%X,%d},\n" % (cp, pair, 1 if t == "o" else 2))
out.append("};\n\n")

