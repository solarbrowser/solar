#!/usr/bin/env python3
"""Generates src/text/UnicodeTables.cpp from the Unicode Character Database: the properties that text layout needs (line breaking, east asian
width, emoji, grapheme and word breaking, bidi, general category, case mapping).

usage: tools/gentext.py UCD_DIR > src/text/UnicodeTables.cpp   (UCD_DIR holds the files named in FILES, from https://www.unicode.org/Public/<version>/ucd/)
"""
import re
import sys

ucd = sys.argv[1]
VERSION = "18.0.0"


def read(name):
    return open(f"{ucd}/{name}", encoding="utf-8").read().splitlines()


def parse_ranges(name, missing_default=True):
    """-> (default, [(first, last, value)]) with @missing lines applied first."""
    missing = []
    entries = []
    for line in read(name):
        m = re.match(r"#\s*@missing:\s*([0-9A-F]+)\.\.([0-9A-F]+);\s*(?:[^;]*;\s*)?([^#;]+)", line)
        if m:
            missing.append((int(m.group(1), 16), int(m.group(2), 16), m.group(3).strip()))
            continue
        line = line.split("#")[0].strip()
        if not line:
            continue
        parts = [p.strip() for p in line.split(";")]
        rng = parts[0]
        if ".." in rng:
            a, b = rng.split("..")
        else:
            a = b = rng
        entries.append((int(a, 16), int(b, 16), parts[1]))
    return missing, entries


def table(name, default, key=None):
    """A dense lookup applied in file order: later lines win. Returns a sorted list of merged ranges (value != default)."""
    missing, entries = parse_ranges(name)
    cells = {}
    spans = []
    for first, last, value in missing:
        spans.append((first, last, value))
    for first, last, value in entries:
        spans.append((first, last, value))
    # paint into a list of runs
    runs = [(0, 0x10FFFF, default)]
    for first, last, value in spans:
        out = []
        for a, b, v in runs:
            if b < first or a > last:
                out.append((a, b, v))
                continue
            if a < first:
                out.append((a, first - 1, v))
            out.append((max(a, first), min(b, last), value))
            if b > last:
                out.append((last + 1, b, v))
        runs = out
    runs.sort()
    merged = []
    for a, b, v in runs:
        if merged and merged[-1][2] == v and merged[-1][1] + 1 == a:
            merged[-1] = (merged[-1][0], b, v)
        else:
            merged.append((a, b, v))
    return [(a, b, v) for a, b, v in merged if v != default]


def emit_enum(title, values):
    return "// %s: %s\n" % (title, ", ".join("%d %s" % (i, v) for i, v in enumerate(values)))


out = []
out.append("// Generated by tools/gentext.py from the Unicode Character Database %s: do not edit.\n" % VERSION)
out.append('#include "solar/text/Unicode.h"\n\nnamespace solar::text {\n\nnamespace {\n')


def emit_ranges(cname, ranges, values, comment):
    idx = {v: i for i, v in enumerate(values)}
    out.append(emit_enum(comment, values))
    out.append("const Range %s[] = {\n" % cname)
    line = "  "
    for a, b, v in ranges:
        item = "{0x%X,0x%X,%d}," % (a, b, idx[v])
        if len(line) + len(item) > 140:
            out.append(line + "\n")
            line = "  "
        line += item
    out.append(line + "\n};\n\n")


