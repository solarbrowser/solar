runs = [(0, 0x10FFFF, "L")]
for first, last, value in missing + entries:
    o = []
    for a, b, v in runs:
        if b < first or a > last:
            o.append((a, b, v)); continue
        if a < first:
            o.append((a, first - 1, v))
        o.append((max(a, first), min(b, last), value))
        if b > last:
            o.append((last + 1, b, v))
    runs = o
runs.sort()
mg = []
