// Usage: EmbedIcons <icon.svg>... > Icons.cpp
// Writes the icons as a C++ source that defines `kIcons`: a table of (name, svg) ending with a null name. The name is the file's, without its directory, its `.svg`, and the set's
// prefix before `--` (mdi--chevron-left.svg is "chevron-left"). The svg is cleaned: one line, a 24 x 24 viewBox, drawn in the colour of the text (the invisible square some sets
// begin with, and the width and height they give, are left out).
#include <cstdio>
#include <fstream>
#include <iterator>
#include <string>

static std::string Clean(const std::string& text) {
  const size_t open = text.find("<svg");
  const size_t start = open == std::string::npos ? open : text.find('>', open);
  const size_t close = text.rfind("</svg>");
  if (start == std::string::npos || close == std::string::npos || close < start) return "";
  std::string inner = text.substr(start + 1, close - start - 1), out;
  // (Blanks between tags go; the contents of the tags are kept as they are.)
  bool inTag = false;
  for (char c : inner) {
    if (c == '<') inTag = true;
    if (c == '\n' || c == '\r' || c == '\t') {
      if (inTag) out += ' ';
      continue;
    }
    if (c == '>') inTag = false;
    if (c == '\'') continue;
    out += c;
  }
  // The invisible square.
  const std::string square = "<path d=\"M0 0h24v24H0z\" fill=\"none\" />";
  for (size_t at; (at = out.find(square)) != std::string::npos;) out.erase(at, square.size());
  const std::string square2 = "<path fill=\"none\" d=\"M0 0h24v24H0z\" />";
  for (size_t at; (at = out.find(square2)) != std::string::npos;) out.erase(at, square2.size());
  size_t first = out.find_first_not_of(' ');
  out = first == std::string::npos ? "" : out.substr(first);
  return "<svg viewBox=\"0 0 24 24\" fill=\"currentColor\">" + out + "</svg>";
}

int main(int argc, char** argv) {
  std::printf("// Generated by tools/EmbedIcons.cpp. Do not edit.\n#include \"solar/gui/Chrome.h\"\n\nnamespace solar::gui {\n\nconst Icon kIcons[] = {\n");
  for (int i = 1; i < argc; ++i) {
    std::ifstream file(argv[i]);
    if (!file) {
      std::fprintf(stderr, "EmbedIcons: cannot open %s\n", argv[i]);
      return 1;
    }
    const std::string text((std::istreambuf_iterator<char>(file)), std::istreambuf_iterator<char>());
    std::string name = argv[i];
    if (const size_t slash = name.rfind('/'); slash != std::string::npos) name = name.substr(slash + 1);
    if (name.size() > 4 && name.compare(name.size() - 4, 4, ".svg") == 0) name.resize(name.size() - 4);
    if (const size_t prefix = name.find("--"); prefix != std::string::npos) name = name.substr(prefix + 2);
    const std::string svg = Clean(text);
    if (svg.empty()) {
      std::fprintf(stderr, "EmbedIcons: %s is not an svg\n", argv[i]);
      return 1;
    }
    std::printf("  {\"%s\", R\"SOLAR_ICON(%s)SOLAR_ICON\"},\n", name.c_str(), svg.c_str());
  }
  std::printf("  {nullptr, nullptr},\n};\n\n}  // namespace solar::gui\n");
  return 0;
}
